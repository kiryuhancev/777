"""Build the cacheable web site; index.html remains the standalone source."""
from pathlib import Path
import hashlib
import base64
import json
import os
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
html = ROOT / 'index.html'
source = html.read_text()
# Refuse accidental deployment of a privileged key; public configuration may stay blank.
public_key = re.search(r"supabaseAnonKey:\s*'([^']*)'", source)
if public_key and public_key[1]:
    value = public_key[1]
    if not value.startswith('sb_publishable_'):
        try:
            payload = value.split('.')[1]
            role = json.loads(base64.urlsafe_b64decode(payload + '=' * (-len(payload) % 4))).get('role')
        except (ValueError, IndexError, UnicodeDecodeError):
            role = None
        if role != 'anon':
            raise SystemExit('VAULT frontend accepts only a public publishable/anon key')
site = ROOT / '_site'
site.mkdir(exist_ok=True)
asset_dir = site / 'assets' / 'embedded'
asset_dir.mkdir(parents=True, exist_ok=True)
assets = {}
image_types = {'png':'png', 'webp':'webp', 'jpeg':'jpg', 'gif':'gif', 'svg+xml':'svg', 'avif':'avif'}

def external_image(match):
    mime, encoded = match.groups()
    extension = image_types.get(mime)
    if not extension:
        return match[0]
    payload = base64.b64decode(encoded, validate=True)
    name = hashlib.sha256(payload).hexdigest() + '.' + extension
    if name not in assets:
        (asset_dir / name).write_bytes(payload)
        assets[name] = len(payload)
    return 'assets/embedded/' + name

# Only image URLs change. The SDK's data URL/currentScript contract is preserved.
source = re.sub(r'data:image/([a-zA-Z0-9.+-]+);base64,([A-Za-z0-9+/=]+)', external_image, source)
scripts = re.findall(r'<script\b[^>]*>(.*?)</script>', source, re.S | re.I)
if not scripts or not re.search(r'<title>(?:DIGITAL DERBY|VAULT)', source):
    raise SystemExit('Expected the standalone game with embedded JavaScript')
Path('/tmp/digital-derby-release.js').write_text('\n'.join(scripts))
built = source.encode('utf-8')
(site / 'index.html').write_bytes(built)
# Prune only files generated by this builder, never arbitrary site assets.
for old in asset_dir.iterdir():
    if old.name not in assets and re.fullmatch(r'[0-9a-f]{64}\.(png|webp|jpg|gif|svg|avif)', old.name):
        old.unlink()
html_hash = hashlib.sha256(built).hexdigest()
(site / '.nojekyll').touch()
commit = os.environ.get('GITHUB_SHA') or subprocess.check_output(
    ['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip()
(site / 'version.json').write_text(json.dumps({
    'version': 'v47', 'commit': commit,
    'htmlSha256': html_hash, 'imageCount':len(assets), 'imageBytes':sum(assets.values()),
}, indent=2) + '\n')
print(f'Built {len(built)} HTML bytes + {len(assets)} unique images ({sum(assets.values())} bytes); standalone source {html.stat().st_size} bytes')
output = os.environ.get('GITHUB_OUTPUT')
if output:
    with open(output, 'a') as stream:
        stream.write('html_sha256=' + html_hash + '\n')
